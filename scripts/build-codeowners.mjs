#!/usr/bin/env node
// Generates .github/CODEOWNERS from each production skill's `owner:`
// frontmatter. This is what makes "editing a Production Ready skill needs
// the owner's review" a real, GitHub-enforced rule instead of a line in a
// doc — once this file exists and branch protection has "require review
// from Code Owners" turned on, GitHub blocks a merge until that person
// approves, automatically.
//
// `owner:` must be a GitHub username or team (e.g. `owner: @audris` or
// `owner: @snowpackdata/data-science`) — a plain display name won't
// resolve to a reviewer.
//
// Run: node scripts/build-codeowners.mjs

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const PRODUCTION_DIR = "skills/production";
const OUTPUT_PATH = ".github/CODEOWNERS";

function parseFrontmatter(text) {
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  const fm = {};
  for (const line of match[1].split("\n")) {
    const m = line.match(/^([A-Za-z0-9_]+):\s*(.*)$/);
    if (m) fm[m[1]] = m[2].trim();
  }
  return fm;
}

function main() {
  if (!existsSync(PRODUCTION_DIR)) {
    console.log("No production skills yet — nothing to write.");
    return;
  }

  const lines = [
    "# Generated by scripts/build-codeowners.mjs — do not hand-edit.",
    "# Each production-ready skill requires its named owner's review.",
    "",
  ];
  const missingOwners = [];

  for (const dir of readdirSync(PRODUCTION_DIR, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const skillMdPath = join(PRODUCTION_DIR, dir.name, "SKILL.md");
    if (!existsSync(skillMdPath)) continue;

    const fm = parseFrontmatter(readFileSync(skillMdPath, "utf8"));
    const owner = fm?.owner;

    if (!owner) {
      missingOwners.push(dir.name);
      continue;
    }
    const handle = owner.startsWith("@") ? owner : `@${owner}`;
    lines.push(`/${PRODUCTION_DIR}/${dir.name}/ ${handle}`);
  }

  writeFileSync(OUTPUT_PATH, lines.join("\n") + "\n");
  console.log(`Wrote ${OUTPUT_PATH}.`);

  if (missingOwners.length) {
    console.error(
      `Missing "owner:" frontmatter for: ${missingOwners.join(", ")} — these production skills have no enforced reviewer.`
    );
    process.exit(1);
  }
}

main();
